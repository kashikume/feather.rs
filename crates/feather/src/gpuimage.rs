//! Sampled images on the GPU: atlases uploaded for drawing, and the sampler they share.

use std::ptr::copy_nonoverlapping as memcpy;

use anyhow::{bail, Result};
use vulkanalia::prelude::v1_0::*;

use super::buffers::create_buffer;
use super::images::{
    copy_buffer_to_image, create_image, create_image_view, transition_image_layout,
};
use super::other::{begin_single_time_commands, end_single_time_commands};
use super::physicaldevice::DeviceFeatures;

/// Format of every sampled image: 8-bit RGBA with sRGB-encoded colors (as PNG files store them).
const FORMAT: vk::Format = vk::Format::R8G8B8A8_SRGB;

/// What uploading to the GPU needs.
pub struct UploadContext<'a> {
    pub instance: &'a Instance,
    pub device: &'a Device,
    pub physical_device: vk::PhysicalDevice,
    pub command_pool: vk::CommandPool,
    pub queue: vk::Queue,
}

/// An RGBA image on the GPU, with mipmaps when the device can generate them, ready to be
/// sampled by fragment shaders.
pub struct GpuImage {
    image: vk::Image,
    memory: vk::DeviceMemory,
    pub view: vk::ImageView,
    pub mip_levels: u32,
}

impl GpuImage {
    /// Uploads `pixels` (8-bit RGBA, row by row, `width * height * 4` bytes).
    pub unsafe fn upload_rgba(
        ctx: &UploadContext,
        width: u32,
        height: u32,
        pixels: &[u8],
    ) -> Result<Self> {
        if width == 0 || height == 0 || pixels.len() != width as usize * height as usize * 4 {
            bail!(
                "invalid RGBA image: {width}x{height} with {} bytes",
                pixels.len()
            );
        }
        let device = ctx.device;
        let size = pixels.len() as u64;

        // Mipmaps are generated by blitting, which needs linear filtering of the format.
        let can_blit = ctx
            .instance
            .get_physical_device_format_properties(ctx.physical_device, FORMAT)
            .optimal_tiling_features
            .contains(vk::FormatFeatureFlags::SAMPLED_IMAGE_FILTER_LINEAR);
        let mip_levels = if can_blit {
            32 - width.max(height).leading_zeros()
        } else {
            1
        };

        // Staging buffer

        let (staging_buffer, staging_memory) = create_buffer(
            ctx.instance,
            device,
            &ctx.physical_device,
            size,
            vk::BufferUsageFlags::TRANSFER_SRC,
            vk::MemoryPropertyFlags::HOST_COHERENT | vk::MemoryPropertyFlags::HOST_VISIBLE,
        )?;
        let result = (|| {
            let memory = device.map_memory(staging_memory, 0, size, vk::MemoryMapFlags::empty())?;
            memcpy(pixels.as_ptr(), memory.cast(), pixels.len());
            device.unmap_memory(staging_memory);
            Self::create_from_staging(ctx, staging_buffer, width, height, mip_levels)
        })();
        device.destroy_buffer(staging_buffer, None);
        device.free_memory(staging_memory, None);
        result
    }

    unsafe fn create_from_staging(
        ctx: &UploadContext,
        staging_buffer: vk::Buffer,
        width: u32,
        height: u32,
        mip_levels: u32,
    ) -> Result<Self> {
        let device = ctx.device;
        let (image, memory) = create_image(
            ctx.instance,
            device,
            ctx.physical_device,
            width,
            height,
            mip_levels,
            vk::SampleCountFlags::_1,
            FORMAT,
            vk::ImageTiling::OPTIMAL,
            vk::ImageUsageFlags::SAMPLED
                | vk::ImageUsageFlags::TRANSFER_DST
                | vk::ImageUsageFlags::TRANSFER_SRC,
            vk::MemoryPropertyFlags::DEVICE_LOCAL,
        )?;
        let mut gpu_image = Self {
            image,
            memory,
            view: vk::ImageView::null(),
            mip_levels,
        };

        let result = (|| {
            transition_image_layout(
                device,
                ctx.command_pool,
                ctx.queue,
                image,
                FORMAT,
                vk::ImageLayout::UNDEFINED,
                vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                mip_levels,
            )?;
            copy_buffer_to_image(
                device,
                ctx.command_pool,
                ctx.queue,
                staging_buffer,
                image,
                width,
                height,
            )?;
            if mip_levels > 1 {
                generate_mipmaps(ctx, image, width, height, mip_levels)?;
            } else {
                transition_image_layout(
                    device,
                    ctx.command_pool,
                    ctx.queue,
                    image,
                    FORMAT,
                    vk::ImageLayout::TRANSFER_DST_OPTIMAL,
                    vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL,
                    mip_levels,
                )?;
            }
            gpu_image.view = create_image_view(
                device,
                image,
                FORMAT,
                vk::ImageAspectFlags::COLOR,
                mip_levels,
            )?;
            Ok(())
        })();

        match result {
            Ok(()) => Ok(gpu_image),
            Err(e) => {
                gpu_image.destroy(device);
                Err(e)
            }
        }
    }

    pub unsafe fn destroy(&self, device: &Device) {
        if self.view != vk::ImageView::null() {
            device.destroy_image_view(self.view, None);
        }
        device.destroy_image(self.image, None);
        device.free_memory(self.memory, None);
    }
}

/// Fills mip levels 1.. by halving the previous level, and leaves every level in
/// `SHADER_READ_ONLY_OPTIMAL`. Level 0 must hold the image in `TRANSFER_DST_OPTIMAL`.
unsafe fn generate_mipmaps(
    ctx: &UploadContext,
    image: vk::Image,
    width: u32,
    height: u32,
    mip_levels: u32,
) -> Result<()> {
    let device = ctx.device;
    let command_buffer = begin_single_time_commands(device, &ctx.command_pool)?;

    let subresource = vk::ImageSubresourceRange::builder()
        .aspect_mask(vk::ImageAspectFlags::COLOR)
        .base_array_layer(0)
        .layer_count(1)
        .level_count(1);

    let mut barrier = vk::ImageMemoryBarrier::builder()
        .image(image)
        .src_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
        .dst_queue_family_index(vk::QUEUE_FAMILY_IGNORED)
        .subresource_range(subresource);

    let mut mip_width = width as i32;
    let mut mip_height = height as i32;

    for i in 1..mip_levels {
        // Level i-1: written -> blit source.
        barrier.subresource_range.base_mip_level = i - 1;
        barrier.old_layout = vk::ImageLayout::TRANSFER_DST_OPTIMAL;
        barrier.new_layout = vk::ImageLayout::TRANSFER_SRC_OPTIMAL;
        barrier.src_access_mask = vk::AccessFlags::TRANSFER_WRITE;
        barrier.dst_access_mask = vk::AccessFlags::TRANSFER_READ;
        device.cmd_pipeline_barrier(
            command_buffer,
            vk::PipelineStageFlags::TRANSFER,
            vk::PipelineStageFlags::TRANSFER,
            vk::DependencyFlags::empty(),
            &[] as &[vk::MemoryBarrier],
            &[] as &[vk::BufferMemoryBarrier],
            &[barrier],
        );

        let next_width = (mip_width / 2).max(1);
        let next_height = (mip_height / 2).max(1);
        let layers = |level| {
            vk::ImageSubresourceLayers::builder()
                .aspect_mask(vk::ImageAspectFlags::COLOR)
                .mip_level(level)
                .base_array_layer(0)
                .layer_count(1)
        };
        let blit = vk::ImageBlit::builder()
            .src_offsets([
                vk::Offset3D { x: 0, y: 0, z: 0 },
                vk::Offset3D {
                    x: mip_width,
                    y: mip_height,
                    z: 1,
                },
            ])
            .src_subresource(layers(i - 1))
            .dst_offsets([
                vk::Offset3D { x: 0, y: 0, z: 0 },
                vk::Offset3D {
                    x: next_width,
                    y: next_height,
                    z: 1,
                },
            ])
            .dst_subresource(layers(i));
        device.cmd_blit_image(
            command_buffer,
            image,
            vk::ImageLayout::TRANSFER_SRC_OPTIMAL,
            image,
            vk::ImageLayout::TRANSFER_DST_OPTIMAL,
            &[blit],
            vk::Filter::LINEAR,
        );

        // Level i-1 is final: blit source -> shader read.
        barrier.old_layout = vk::ImageLayout::TRANSFER_SRC_OPTIMAL;
        barrier.new_layout = vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL;
        barrier.src_access_mask = vk::AccessFlags::TRANSFER_READ;
        barrier.dst_access_mask = vk::AccessFlags::SHADER_READ;
        device.cmd_pipeline_barrier(
            command_buffer,
            vk::PipelineStageFlags::TRANSFER,
            vk::PipelineStageFlags::FRAGMENT_SHADER,
            vk::DependencyFlags::empty(),
            &[] as &[vk::MemoryBarrier],
            &[] as &[vk::BufferMemoryBarrier],
            &[barrier],
        );

        mip_width = next_width;
        mip_height = next_height;
    }

    // The last level was only written.
    barrier.subresource_range.base_mip_level = mip_levels - 1;
    barrier.old_layout = vk::ImageLayout::TRANSFER_DST_OPTIMAL;
    barrier.new_layout = vk::ImageLayout::SHADER_READ_ONLY_OPTIMAL;
    barrier.src_access_mask = vk::AccessFlags::TRANSFER_WRITE;
    barrier.dst_access_mask = vk::AccessFlags::SHADER_READ;
    device.cmd_pipeline_barrier(
        command_buffer,
        vk::PipelineStageFlags::TRANSFER,
        vk::PipelineStageFlags::FRAGMENT_SHADER,
        vk::DependencyFlags::empty(),
        &[] as &[vk::MemoryBarrier],
        &[] as &[vk::BufferMemoryBarrier],
        &[barrier],
    );

    end_single_time_commands(device, &ctx.command_pool, &ctx.queue, command_buffer)?;
    Ok(())
}

/// The sampler used for every texture: linear filtering with mipmaps, anisotropic filtering,
/// repeating texture coordinates. Anisotropic filtering (up to 16x) only when the device has it
/// (`features`).
pub unsafe fn create_texture_sampler(
    device: &Device,
    features: &DeviceFeatures,
) -> Result<vk::Sampler> {
    let info = vk::SamplerCreateInfo::builder()
        .mag_filter(vk::Filter::LINEAR)
        .min_filter(vk::Filter::LINEAR)
        .address_mode_u(vk::SamplerAddressMode::REPEAT)
        .address_mode_v(vk::SamplerAddressMode::REPEAT)
        .address_mode_w(vk::SamplerAddressMode::REPEAT)
        .anisotropy_enable(features.sampler_anisotropy)
        .max_anisotropy(features.max_sampler_anisotropy.min(16.0))
        .border_color(vk::BorderColor::INT_OPAQUE_BLACK)
        .unnormalized_coordinates(false)
        .compare_enable(false)
        .compare_op(vk::CompareOp::ALWAYS)
        .mipmap_mode(vk::SamplerMipmapMode::LINEAR)
        .min_lod(0.0)
        .max_lod(vk::LOD_CLAMP_NONE)
        .mip_lod_bias(0.0);

    Ok(device.create_sampler(&info, None)?)
}
